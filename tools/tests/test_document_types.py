ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import _document_types as types  # noqa: E402

PUBLICATION = """\
schema_version = 1
id = "claude/fixture/leaf"
kind = "fixture-kind"
profile = "guidance/fixture.md"
source_format = "latex"
entrypoint = "main.tex"

[[outputs]]
id = "claude/fixture/leaf"
role = "canonical"
entrypoint = "main.tex"
derivation = "authored"

[[structure]]
role = "body"
source = "main.tex"
"""

TYPE = """\
schema = 1
record_type = "document-type"
id = "fixture-v1"
description = "A fixture."
kinds = ["fixture-kind"]

[editions.main]
role = "canonical"
template = "main.tex"
entrypoint = "main.tex"
fields = ["pdftitle"]
optional_fields = { subtitle = "" }
regions = ["body"]
optional_regions = ["apparatus"]
options = { closing = "plain" }

[editions.synthesis]
role = "synthesis"
template = "synthesis.tex"
entrypoint = "synthesis.tex"
fields = ["pdftitle"]
regions = ["body"]
"""

TEMPLATE = """\
%% a template comment is never copied
\\input{common/preamble}
%@ input? format
\\hypersetup{pdftitle={@{pdftitle}}}
\\begin{document}
\\title{@{subtitle}}
%@ region body
%@ slot fake/page
%@ region apparatus
%@ option closing
\\end{document}
"""


def fake_projection(calls: list):
    outputs = {"page": "generated/fake.tex", "unslotted": "generated/other.tex"}

    def render(context):
        calls.append((context.document, context.outputs))
        files = {outputs[key]: f"% {key} for {context.document}\n" for key in context.outputs}
        files["research/fake.toml"] = "x = 1\n"
        return files
    return SimpleNamespace(NAME="fake", OUTPUTS=outputs, render=render)


class FixtureTests(unittest.TestCase):
    def setUp(self):
        scratch = ROOT / ".scratch/tests/document-types"
        scratch.mkdir(parents=True, exist_ok=True)
        self.temp = tempfile.TemporaryDirectory(dir=scratch)
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        kind = self.root / types.TYPES_DIR / "fixture-v1"
        (kind / "closing").mkdir(parents=True)
        (kind / "type.toml").write_text(TYPE)
        (kind / "main.tex").write_text(TEMPLATE)
        (kind / "synthesis.tex").write_text("%@ region body\n")
        (kind / "closing/plain.tex").write_text("%@ input generation-metadata\n")
        (kind / "closing/boxed.tex").write_text("\\fbox{x}\n%@ input generation-metadata\n")
        self.leaf = self.root / "src/claude/fixture/leaf"
        (self.leaf / "sections").mkdir(parents=True)
        for name in ("sections/10-a.tex", "sections/20-b.tex", "sections/90-c.tex",
                     "generation-metadata.tex"):
            (self.leaf / name).write_text("x\n")
        self.calls: list = []
        self.projections = {"fake": fake_projection(self.calls)}

    def declare(self, extra: str = "") -> None:
        (self.leaf / "publication.toml").write_text(PUBLICATION + """
[document]
type = "fixture-v1"
subtitle = 'Shared \\emph{sub}'

[document.main]
pdftitle = 'Title'
body = ["sections/10-a", '\\Needspace{12\\baselineskip}', "sections/20-b"]
apparatus = ["sections/90-c"]
""" + extra)

    def render(self) -> str:
        decl = types.declaration(self.root, self.leaf)
        return types.render_edition(decl, "main", self.projections)[0]

    def test_a_type_is_found_by_its_directory(self):
        found = types.discover_types(self.root)
        self.assertEqual(list(found), ["fixture-v1"])
        self.assertEqual(found["fixture-v1"].option_values("closing"), ("boxed", "plain"))

    def test_the_entrypoint_is_literal_tex_in_template_order(self):
        self.declare()
        self.assertEqual(self.render().splitlines()[2:], [
            "\\input{common/preamble}",
            "\\hypersetup{pdftitle={Title}}",
            "\\begin{document}",
            "\\title{Shared \\emph{sub}}",
            "\\input{fixture/leaf/sections/10-a}",
            "\\Needspace{12\\baselineskip}",
            "\\input{fixture/leaf/sections/20-b}",
            "\\input{fixture/leaf/generated/fake}",
            "\\input{fixture/leaf/sections/90-c}",
            "\\input{fixture/leaf/generation-metadata}",
            "\\end{document}",
        ])
        self.assertTrue(self.render().startswith("% Generated by tools/tpt document-types refresh"))

    def test_an_optional_leaf_input_appears_only_when_the_file_exists(self):
        self.declare()
        (self.leaf / "format.tex").write_text("\\newcommand{\\x}{}\n")
        self.assertIn("\\input{fixture/leaf/format}", self.render())

    def test_an_option_selects_its_fragment(self):
        self.declare()
        text = (self.leaf / "publication.toml").read_text().replace(
            "pdftitle = 'Title'", "pdftitle = 'Title'\nclosing = \"boxed\"")
        (self.leaf / "publication.toml").write_text(text)
        self.assertIn("\\fbox{x}", self.render())

    def test_a_template_may_name_the_leaf_path_and_a_chosen_option(self):
        self.declare()
        kind = self.root / types.TYPES_DIR / "fixture-v1"
        (kind / "main.tex").write_text(TEMPLATE.replace(
            "\\begin{document}\n",
            "\\newcommand{\\Meta}{\\input{@{document}/generation-metadata}%}\n"
            "\\input{shared/@{closing}-sheet}\n\\begin{document}\n"))
        text = self.render()
        self.assertIn("\\newcommand{\\Meta}{\\input{fixture/leaf/generation-metadata}%}", text)
        self.assertIn("\\input{shared/plain-sheet}", text)

    def test_a_type_may_not_declare_a_built_in_reference(self):
        kind = self.root / types.TYPES_DIR / "fixture-v1"
        (kind / "type.toml").write_text(TYPE.replace(
            'optional_fields = { subtitle = "" }',
            'optional_fields = { subtitle = "", document = "" }', 1))
        with self.assertRaises(types.DocumentTypeError) as caught:
            types.discover_types(self.root)
        self.assertIn("built-in", str(caught.exception))

    def test_an_if_block_keeps_its_lines_only_for_a_non_empty_field(self):
        self.declare()
        kind = self.root / types.TYPES_DIR / "fixture-v1"
        (kind / "closing/plain.tex").write_text(
            "%@ if subtitle\n\\vspace{1em}\n%@ if pdftitle\n{@{subtitle}}\n%@ end\n%@ end\n"
            "%@ input generation-metadata\n")
        self.assertIn("\\vspace{1em}\n{Shared \\emph{sub}}\n", self.render())
        path = self.leaf / "publication.toml"
        path.write_text(path.read_text().replace("subtitle = 'Shared \\emph{sub}'", "subtitle = ''"))
        rendered = self.render()
        self.assertNotIn("vspace", rendered)
        self.assertIn("\\input{fixture/leaf/generation-metadata}", rendered)

    def test_an_unbalanced_or_undeclared_if_is_refused(self):
        self.declare()
        kind = self.root / types.TYPES_DIR / "fixture-v1"
        for fragment, needle in (
                ("%@ if subtitle\nx\n", "without %@ end"),
                ("x\n%@ end\n", "without %@ if"),
                ("%@ if surprise\nx\n%@ end\n", "not declared"),
        ):
            with self.subTest(needle=needle):
                (kind / "closing/plain.tex").write_text(fragment)
                with self.assertRaises(types.DocumentTypeError) as caught:
                    self.render()
                self.assertIn(needle, str(caught.exception))

    def test_refusals(self):
        cases = {
            "unknown field": "\n[document.homily]\npdftitle = 'x'\n",
        }
        self.declare(cases["unknown field"])
        with self.assertRaises(types.DocumentTypeError):
            types.declaration(self.root, self.leaf)
        for replacement, needle in (
            (("pdftitle = 'Title'", "pdftitle = 'Title'\nsurprise = 'x'"), "not declared"),
            (("pdftitle = 'Title'\n", ""), "requires field"),
            (('"sections/20-b"', '"sections/missing"'), "no leaf file"),
            (("pdftitle = 'Title'", "pdftitle = 'Title'\nclosing = \"gold\""), "not one of"),
            (('type = "fixture-v1"', 'type = "nope-v1"'), "not a directory"),
        ):
            with self.subTest(needle=needle):
                self.declare()
                path = self.leaf / "publication.toml"
                path.write_text(path.read_text().replace(*replacement))
                with self.assertRaises(types.DocumentTypeError) as caught:
                    self.render()
                self.assertIn(needle, str(caught.exception))

    def test_refresh_writes_projections_and_is_idempotent(self):
        self.declare()
        first = types.refresh(self.root, [self.leaf], check=False, projections=self.projections)
        self.assertEqual(first[0].changed, ("generated/fake.tex", "main.tex", "research/fake.toml"))
        second = types.refresh(self.root, [self.leaf], check=False, projections=self.projections)
        self.assertEqual(second[0].changed, ())
        # Only the output a template slots is asked for, once per refresh.
        self.assertEqual(self.calls, [("fixture/leaf", ("page",))] * 2)

    def test_a_generated_file_nothing_generates_is_reported_then_removed(self):
        self.declare()
        types.refresh(self.root, [self.leaf], check=False, projections=self.projections)
        stray = self.leaf / "generated/retired.tex"
        stray.write_text("% a page whose slot was removed\n")
        found = types.refresh(self.root, [self.leaf], check=True, projections=self.projections)
        self.assertEqual(found[0].orphans, ("generated/retired.tex",))
        self.assertTrue(stray.is_file(), "--check must write nothing")
        types.refresh(self.root, [self.leaf], check=False, projections=self.projections)
        self.assertFalse(stray.exists())

    def test_check_refuses_a_hand_edited_generated_file(self):
        self.declare()
        types.refresh(self.root, [self.leaf], check=False, projections=self.projections)
        path = self.leaf / "main.tex"
        path.write_text(path.read_text() + "% edited\n")
        found = types.refresh(self.root, [self.leaf], check=True, projections=self.projections)
        self.assertEqual(found[0].changed, ("main.tex",))
        self.assertTrue(path.read_text().endswith("% edited\n"), "--check must write nothing")

    def test_a_written_companion_must_have_its_edition_but_a_future_one_need_not(self):
        self.declare()
        path = self.leaf / "publication.toml"
        path.write_text(path.read_text().replace("""[[structure]]""", """[[outputs]]
id = "claude/fixture/leaf-synthesis"
role = "synthesis"
entrypoint = "synthesis.tex"
derivation = "authored"

[[structure]]"""))
        self.assertIsNotNone(types.declaration(self.root, self.leaf))
        (self.leaf / "synthesis.tex").write_text("\\input{x}\n")
        with self.assertRaises(types.DocumentTypeError) as caught:
            types.declaration(self.root, self.leaf)
        self.assertIn("would stay hand-written", str(caught.exception))

    def test_opted_in_leaves_are_found_by_their_declaration(self):
        self.assertEqual(types.opted_in_leaves(self.root), [])
        self.declare()
        self.assertEqual(types.opted_in_leaves(self.root), [self.leaf])


class RepositoryTypeTests(unittest.TestCase):
    def test_every_type_loads_and_every_slot_names_a_projection(self):
        projections = types.discover_projections()
        found = types.discover_types(ROOT)
        self.assertIn("proper-study-v1", found)
        for document_type in found.values():
            for edition in document_type.editions.values():
                for slot in types.template_slots(document_type, edition):
                    with self.subTest(type=document_type.id, slot=slot):
                        self.assertTrue(types.slot_path(slot, projections).startswith("generated/"))

    def test_the_proper_study_places_the_date_page_in_both_studies(self):
        found = types.discover_types(ROOT)["proper-study-v1"]
        self.assertEqual(types.template_slots(found, found.editions["main"]),
                         ["scriptural-date-location/section"])
        self.assertEqual(types.template_slots(found, found.editions["synthesis"]),
                         ["scriptural-date-location/page"])
        self.assertEqual(types.template_slots(found, found.editions["homily"]), [])


if __name__ == "__main__":
    unittest.main()
