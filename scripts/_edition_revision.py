class RevisionError(RuntimeError):
    """The stamp cannot be derived, and a guessed one would be wrong."""


@dataclasses.dataclass(frozen=True)
class Revision:
    """One edition's derived stamp and what it was derived from."""

    provider: str
    document: str
    timestamp: str
    commit: str | None
    uncommitted: bool
    closure: tuple[str, ...]
    root: Path = dataclasses.field(default=ROOT, compare=False, repr=False)

    @property
    def display(self) -> str:
        """The exact value every rendering prints after "Last revised (UTC):"."""
        return f"{self.timestamp} ({UNCOMMITTED})" if self.uncommitted else self.timestamp

    def tex(self) -> str:
        """The build-supplied TeX the shared preamble reads as \\jobname.revision.tex."""
        lines = [
            f"% Derived by scripts/_edition_revision.py for {self.provider}/{self.document};",
            "% a build product, never tracked or edited.",
        ]
        if self.uncommitted:
            lines.append("% sources: " + self.sources_digest())
        lines.append(f"\\AIDocumentRevisionTimestamp{{{self.timestamp}}}")
        if self.uncommitted:
            lines.append("\\AIDocumentRevisionUncommitted")
        return "\n".join(lines) + "\n"

    def sources_digest(self) -> str:
        digest = hashlib.sha256()
        for value in self.closure:
            path = self.root / value
            digest.update(value.encode() + b"\0")
            digest.update(hashlib.sha256(path.read_bytes()).digest() if path.is_file() else b"missing")
        return digest.hexdigest()

    def record(self) -> dict:
        return {"provider": self.provider, "document": self.document, "timestamp": self.timestamp,
                "display": self.display, "commit": self.commit, "uncommitted": self.uncommitted,
                "closure": list(self.closure)}


def _git(root: Path, *arguments: str) -> str:
    environment = {key: value for key, value in os.environ.items()
                   if key not in {"GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"}}
    environment["GIT_LITERAL_PATHSPECS"] = "1"  # closure paths are files, never patterns
    try:
        run = subprocess.run(["git", *arguments], cwd=root, env=environment,
                             capture_output=True, text=True)
    except OSError as error:
        raise RevisionError(f"cannot run git: {error}") from error
    if run.returncode:
        raise RevisionError(f"git {arguments[0]} failed: {run.stderr.strip()[-500:]}")
    return run.stdout


class Repository:
    """One read of a work tree's state, shared across many editions."""

    def __init__(self, root: Path = ROOT):
        self.root = Path(root).resolve()
        try:
            inside = _git(self.root, "rev-parse", "--is-inside-work-tree").strip()
        except RevisionError as error:
            raise RevisionError(
                f"{self.root} is not a git work tree; an edition's revision stamp is "
                "derived from its history and cannot be built without it") from error
        top = Path(_git(self.root, "rev-parse", "--show-toplevel").strip()).resolve()
        if inside != "true" or top != self.root:
            raise RevisionError(f"{self.root} is not the top of a git work tree")
        if _git(self.root, "rev-parse", "--is-shallow-repository").strip() != "false":
            raise RevisionError(
                "this clone is shallow, so the last commit to change an edition's sources "
                "may be missing from it; revision stamps need full history "
                "(git fetch --unshallow, or actions/checkout with fetch-depth: 0)")
        self._tracked: set[str] | None = None
        self._changed: set[str] | None = None
        self._pre_images: dict[str, tuple[str | None, set[str]]] = {}
        # Stamps `prefetch_revisions` derived for this same state, or the
        # error deriving each raised; `revision` answers from them unchanged.
        self._revisions: dict[tuple[str, str], object] = {}

    def pre_image(self, commit: str) -> tuple[str | None, set[str]]:
        """A commit's first parent and the paths it changed, read without blobs."""
        if commit not in self._pre_images:
            parents = _git(self.root, "rev-list", "--parents", "-n", "1", commit).split()[1:]
            changed = set()
            if parents:
                changed = {line for line in _git(self.root, "diff", "--name-only", "--no-renames", "-z",
                                                 parents[0], commit, "--", "src", "scripts", "tools").split("\0") if line}
            self._pre_images[commit] = (parents[0] if parents else None, changed)
        return self._pre_images[commit]

    def tracked(self) -> set[str]:
        if self._tracked is None:
            output = _git(self.root, "ls-files", "-z", "--", "src", "scripts", "tools")
            self._tracked = {value for value in output.split("\0") if value}
        return self._tracked

    def changed(self) -> set[str]:
        """Content and generator paths differing from HEAD, including untracked files."""
        if self._changed is None:
            output = _git(self.root, "status", "--porcelain=v1", "-z", "--untracked-files=all",
                          "--no-renames", "--", "src", "scripts", "tools")
            self._changed = {entry[3:] for entry in output.split("\0") if len(entry) > 3}
        return self._changed


def entrypoint(root: Path, provider: str, document: str, *, assembly=None) -> Path:
    """The file an edition id typesets, by the rule Make and the gate share."""
    if provider not in PROVIDERS:
        raise RevisionError(f"unknown provider: {provider}")
    if (not document or document.startswith("/") or ".." in document.split("/")
            or "\\" in document):
        raise RevisionError(f"unsafe document id: {document!r}")
    source_root = root / "src" / provider
    assembly = Assembly(root) if assembly is None else assembly
    main = source_root / document / "main.tex"
    if assembly.is_file(main):
        return main
    try:
        owner = companion_owner(source_root, document)
    except (OSError, ValueError) as error:
        raise RevisionError(str(error)) from error
    if owner is not None:
        return owner[1]
    for suffix, name in (("-synthesis", "synthesis.tex"), ("-homily", "homily.tex")):
        if document.endswith(suffix):
            candidate = source_root / document.removesuffix(suffix) / name
            if assembly.is_file(candidate):
                return candidate
    raise RevisionError(f"no edition entrypoint for {provider}/{document}")


def _resolve(root: Path, provider_root: Path, path: Path, argument: str,
             suffixes: tuple[str, ...], *, assembly=None) -> Path | None:
    argument = argument.strip()
    if not argument or argument.startswith("/") or ".." in argument.split("/"):
        raise RevisionError(f"{path.relative_to(root)}: unsafe input {argument!r}")
    for base in (root / "src", provider_root, path.parent):
        for suffix in suffixes:
            candidate = base / (argument + suffix)
            exists = assembly.is_file(candidate) if assembly is not None else candidate.is_file()
            if exists:
                resolved = candidate.resolve()
                if not resolved.is_relative_to(root):
                    raise RevisionError(f"{path.relative_to(root)}: input escapes the repository")
                return resolved
    return None


def _expand(argument: str, definitions: dict[str, set[str]]) -> list[str] | None:
    """Every literal spelling of a macro-built path, or None while one is unknown."""
    values = [argument]
    for _ in range(16):
        if not any(MACRO_RE.search(value) for value in values):
            return sorted(set(values))
        expanded = []
        for value in values:
            names = MACRO_RE.findall(value)
            if any(name not in definitions for name in names):
                return None
            parts = MACRO_RE.split(value)
            choices = [[part] if index % 2 == 0 else sorted(definitions[part])
                       for index, part in enumerate(parts)]
            expanded.extend("".join(choice) for choice in itertools.product(*choices))
        values = expanded
    return None


@functools.cache
def _dictionary_generator(root: Path):
    path = root / "tools" / "render-sanctuary-dictionary"
    name = "_revision_dictionary_" + hashlib.sha256(str(root).encode()).hexdigest()
    loader = importlib.machinery.SourceFileLoader(name, str(path))
    module = importlib.util.module_from_spec(importlib.util.spec_from_loader(name, loader))
    sys.modules[name] = module
    loader.exec_module(module)
    return module


def _render_data(root: Path, provider_root: Path, entry: Path) -> set[Path]:
    manifest = entry.parent / "publication.toml"
    if not manifest.is_file():
        return set()
    try:
        data = load_manifest(root, manifest, output_entrypoint=entry.name)
    except (OSError, SchemaError, ValueError) as error:
        raise RevisionError(f"cannot read {manifest.relative_to(root)}: {error}") from error
    role = next((output.get("role") for output in data.get("outputs", [])
                 if output.get("entrypoint") == entry.name), ENTRYPOINTS.get(entry.name))
    result = set()
    for item in data.get("structure", []):
        if item.get("role") not in RENDER_DATA_ROLES:
            continue
        if item.get("outputs") and role not in item["outputs"]:
            continue
        for path in _structure_paths(root, data, item):
            if path.is_file() and path.suffix in RENDER_DATA_SUFFIXES:
                resolved = path.resolve()
                if resolved.is_relative_to(provider_root):
                    result.add(resolved)
    declaration = data.get("document", {})
    if declaration.get("type") == "sanctuary-dictionary-v1":
        selection = declaration.get(entry.stem, {}).get("selection", declaration.get("selection"))
        generator = _dictionary_generator(root)
        try:
            notes = generator.edition_source_note_inputs(root, entry.parent.parent, selection)
        except (OSError, ValueError) as error:
            raise RevisionError(f"cannot resolve dictionary source notes: {error}") from error
        for path in {*notes, root / "tools" / "render-sanctuary-dictionary"}:
            resolved = path.resolve()
            if not resolved.is_relative_to(root) or not resolved.is_file():
                raise RevisionError(f"dictionary source-note input is missing or outside the repository: {path}")
            result.add(resolved)
    return result


@dataclasses.dataclass(frozen=True)
class Closure:
    paths: tuple[str, ...]
    generated: frozenset[str]


def closure(root: Path, provider: str, entry: Path, *, assembly=None) -> Closure:
    """The repository paths whose commits revise this edition; see the module text."""
    root = Path(root).resolve()
    provider_root = (root / "src" / provider).resolve()
    entry = entry.resolve()
    assembly = Assembly(root) if assembly is None else assembly
    seen: set[Path] = set()
    definitions: dict[str, set[str]] = {}
    computed: list[tuple[Path, str]] = []
    graphics: set[Path] = set()
    pending = [entry]

    def walk() -> None:
        while pending:
            path = pending.pop()
            if path in seen:
                continue
            seen.add(path)
            if path.suffix not in TEXT_SUFFIXES:
                continue
            text = active_tex(assembly.read_text(path))
            for groups in DEFINITION_RE.findall(text):
                name, body = groups[0] or groups[1], groups[2].strip()
                definitions.setdefault(name, set()).add(body)
            for argument in INPUT_RE.findall(text):
                if "#" in argument:
                    continue  # a parameter inside a definition; its callers are read where they occur
                if "\\" in argument:
                    # The contribution log is outside every closure, so where a
                    # macro-built path to it points cannot matter.
                    if argument.strip().rsplit("/", 1)[-1] not in {GENERATION_METADATA, "generation-metadata"}:
                        computed.append((path, argument))
                    continue
                target = _resolve(root, provider_root, path, argument, ("", ".tex"), assembly=assembly)
                if target is None:
                    raise RevisionError(f"{path.relative_to(root)}: unresolved input {argument}")
                pending.append(target)
            for argument in GRAPHICS_RE.findall(text):
                if "\\" in argument or "#" in argument:
                    continue
                target = _resolve(root, provider_root, path, argument, GRAPHIC_SUFFIXES, assembly=assembly)
                if target is not None:
                    graphics.add(target)

    walk()
    resolved: set[tuple[Path, str]] = set()
    while True:
        progress = False
        for path, argument in computed:
            if (path, argument) in resolved:
                continue
            spellings = _expand(argument, definitions)
            if spellings is None:
                continue
            for spelling in spellings:
                target = _resolve(root, provider_root, path, spelling, ("", ".tex"), assembly=assembly)
                if target is None:
                    raise RevisionError(
                        f"{path.relative_to(root)}: computed input {argument} expands to "
                        f"{spelling}, which does not exist")
                pending.append(target)
            resolved.add((path, argument))
            progress = True
        if not progress:
            break
        walk()
    unresolved = sorted({argument for path, argument in computed if (path, argument) not in resolved})
    if unresolved:
        raise RevisionError(
            f"{entry.relative_to(root)}: cannot expand computed input(s) {', '.join(unresolved)}; "
            "an edition's revision stamp needs every source it reads")

    members = {path for path in seen | graphics
               if path.is_relative_to(provider_root) and path.name != GENERATION_METADATA}
    members.update(_render_data(root, provider_root, entry))
    virtual = {path for path in members if assembly.generated(path) is not None}
    for path in virtual:
        members.update(assembly.content_dependencies(path))
    members.difference_update(virtual)
    generated = set()
    for path in members:
        if path.name in ENTRYPOINTS and path.suffix == ".tex":
            with path.open(encoding="utf-8") as stream:
                if stream.readline().startswith(GENERATED_HEADER):
                    generated.add(path)
    relative = lambda path: path.relative_to(root).as_posix()  # noqa: E731
    return Closure(tuple(sorted(relative(path) for path in members)),
                   frozenset(relative(path) for path in generated))


def history_of(root: Path, paths, revision: str = "HEAD") -> list[tuple[int, str, bool]]:
    """(author time, commit, carries ``Edition-Revision: none``) per commit touching paths.

    Trailers are read by ``git log`` formatting, from commit objects alone, so
    a blob-less partial clone answers as a full one does.
    """
    log = _git(root, "log", f"--format=%x1e%at %H%x1f%(trailers:key={TRAILER},valueonly,separator=%x1d)",
               revision, "--", *paths)
    result = []
    for record in log.split("\x1e"):
        if not record.strip():
            continue
        head, _, trailers = record.partition("\x1f")
        seconds, commit = head.split()
        values = [value.strip() for value in trailers.strip().split("\x1d") if value.strip()]
        if any(value != TRAILER_NONE for value in values):
            raise RevisionError(
                f"commit {commit[:12]} carries {TRAILER}: {', '.join(values)}; "
                f"{TRAILER_NONE!r} is the only value it may take")
        result.append((int(seconds), commit, bool(values)))
    return result


MAX_REFACTOR_DEPTH = 16


def _last_revision(repository: "Repository", paths, leaf: str, revision: str, depth: int,
                   followed: set[str]) -> tuple[int, str] | None:
    """The newest unmarked commit that revised these paths as of ``revision``.

    A commit marked ``Edition-Revision: none`` revised no text, but it may have
    moved that text into the files it created, whose own history then starts
    with it. So its own pre-image is read too: the files it changed that the
    edition reads, or that lie in the edition's leaf (where the text came
    from), as they stood in its first parent.
    """
    if depth > MAX_REFACTOR_DEPTH:
        raise RevisionError(f"more than {MAX_REFACTOR_DEPTH} nested {TRAILER}: {TRAILER_NONE} refactors")
    paths = sorted(set(paths))
    if not paths:
        return None
    history = history_of(repository.root, paths, revision)
    best = max(((seconds, commit) for seconds, commit, skipped in history if not skipped), default=None)
    current = set(paths)
    for _seconds, commit, skipped in history:
        if not skipped or commit in followed:
            continue
        followed.add(commit)
        parent, before = repository.pre_image(commit)
        if parent is None:
            continue
        sources = {path for path in before
                   if path in current or (path.startswith(leaf) and _closure_kind(path))}
        found = _last_revision(repository, sources, leaf, parent, depth + 1, followed)
        if found is not None and (best is None or found > best):
            best = found
    return best


def _closure_kind(path: str) -> bool:
    """A file of the kinds a closure holds, not a leaf's records or contribution log."""
    name = path.rsplit("/", 1)[-1]
    parts = path.split("/")
    return (name != GENERATION_METADATA and not {"research", "evaluations", "evaluation"} & set(parts)
            and any(name.endswith(suffix) for suffix in TEXT_SUFFIXES | set(GRAPHIC_SUFFIXES[1:])))


def _now() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc)


def revision_of(root: Path, provider: str, document: str, entry: Path, *,
                repository: Repository | None = None, now: dt.datetime | None = None,
                assembly=None, found: Closure | None = None) -> Revision:
    root = Path(root).resolve()
    repository = Repository(root) if repository is None else repository
    if repository.root != root:
        raise RevisionError("repository state belongs to another root")
    if found is None:
        found = closure(root, provider, entry, assembly=assembly)
    if not found.paths:
        raise RevisionError(f"{provider}/{document}: the edition reads no provider source")
    tracked, changed = repository.tracked(), repository.changed()
    if any(path not in tracked or path in changed for path in found.paths):
        moment = (now or _now()).astimezone(dt.timezone.utc).replace(microsecond=0)
        return Revision(provider, document, moment.strftime(TIMESTAMP_FORMAT), None, True, found.paths, root)
    history = [path for path in found.paths if path not in found.generated]
    if not history:
        raise RevisionError(f"{provider}/{document}: the edition reads no authored provider source")
    leaf = entry.resolve().parent.relative_to(root).as_posix() + "/"
    chosen = _last_revision(repository, history, leaf, "HEAD", 0, set())
    if chosen is None:
        raise RevisionError(
            f"{provider}/{document}: no commit in this history revised its sources "
            f"(every one that changed them carries {TRAILER}: {TRAILER_NONE})")
    moment = dt.datetime.fromtimestamp(chosen[0], dt.timezone.utc)
    return Revision(provider, document, moment.strftime(TIMESTAMP_FORMAT), chosen[1], False, found.paths, root)


def revision(root: Path, provider: str, document: str, *,
             repository: Repository | None = None, now: dt.datetime | None = None,
             assembly=None) -> Revision:
    """The stamp of the edition Make and the gate call ``<provider>/<document>``."""
    root = Path(root).resolve()
    repository = Repository(root) if repository is None else repository
    held = (repository._revisions.get((provider, document))
            if now is None and repository.root == root else None)
    if isinstance(held, Exception):
        raise held
    if held is not None:
        return held
    assembly = Assembly(root) if assembly is None else assembly
    return revision_of(root, provider, document,
                       entrypoint(root, provider, document, assembly=assembly),
                       repository=repository, now=now, assembly=assembly)


def prefetch_revisions(root: Path, editions, *, repository: Repository, assembly=None,
                       jobs: int | None = None) -> None:
    """Derive many editions' stamps into ``repository`` before they are asked for.

    Each stamp is exactly what `revision` derives: the closures are read in
    order through the one assembly, then the ``git log`` walks, which are
    independent and dominate the cost, run concurrently. A derivation's
    error is held and raised where `revision` is later asked for that
    edition, so a batch fails at the same edition, with the same error, as
    it would one at a time.
    """
    from concurrent.futures import ThreadPoolExecutor

    root = Path(root).resolve()
    if repository.root != root:
        raise RevisionError("repository state belongs to another root")
    assembly = Assembly(root) if assembly is None else assembly
    keys = list(dict.fromkeys((provider, document) for provider, document in editions
                              if (provider, document) not in repository._revisions))
    repository.tracked()
    repository.changed()
    closures: dict[tuple[str, str], object] = {}
    for provider, document in keys:
        try:
            entry = entrypoint(root, provider, document, assembly=assembly)
            closures[(provider, document)] = (entry, closure(root, provider, entry, assembly=assembly))
        except Exception as error:  # held, and raised where this edition is asked for
            closures[(provider, document)] = error

    def finish(key):
        held = closures[key]
        if isinstance(held, Exception):
            return held
        entry, found = held
        try:
            return revision_of(root, key[0], key[1], entry, repository=repository,
                               assembly=assembly, found=found)
        except Exception as error:
            return error

    available = getattr(os, "process_cpu_count", os.cpu_count)() or 1
    workers = max(1, min(jobs if jobs is not None else available, 8))
    with ThreadPoolExecutor(max_workers=workers) as pool:
        for key, value in zip(keys, pool.map(finish, keys)):
            repository._revisions[key] = value


def revision_for_entrypoint(root: Path, provider: str, entry: Path, *,
                            repository: Repository | None = None, assembly=None) -> Revision:
    """The stamp of the edition a given entrypoint typesets."""
    root = Path(root).resolve()
    entry = Path(entry).resolve()
    leaf = entry.parent.relative_to((root / "src" / provider).resolve()).as_posix()
    role = ENTRYPOINTS.get(entry.name)
    if role is None:
        raise RevisionError(f"{entry.name} is not an edition entrypoint")
    document = leaf if role == "canonical" else f"{leaf}-{role}"
    return revision_of(root, provider, document, entry, repository=repository, assembly=assembly)


def write(path: Path, value: Revision) -> bool:
    """Write the stamp file only when it changes, so Make rebuilds only then.

    An uncommitted stamp is kept while its sources are byte-identical to the
    ones it was first written for, so repeated builds of the same working tree
    do not each move "now" and retypeset.
    """
    text = value.tex()
    if path.is_file():
        current = path.read_text(encoding="utf-8")
        if current == text:
            return False
        if value.uncommitted and f"% sources: {value.sources_digest()}\n" in current \
                and "\\AIDocumentRevisionUncommitted" in current:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + f".tmp.{os.getpid()}")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    show = commands.add_parser("show", help="print one edition's derived stamp")
    show.add_argument("--provider", required=True)
    show.add_argument("--document", required=True)
    show.add_argument("--json", action="store_true")
    written = commands.add_parser("write", help="write the build's stamp file if it changed")
    written.add_argument("--provider", required=True)
    written.add_argument("--document", required=True)
    written.add_argument("--out", required=True, type=Path)
    arguments = parser.parse_args(argv)
    try:
        value = revision(ROOT, arguments.provider, arguments.document)
        if arguments.command == "write":
            write(arguments.out, value)
        elif arguments.json:
            print(json.dumps(value.record(), indent=1, sort_keys=True))
        else:
            print(value.display)
    except (RevisionError, OSError, UnicodeError) as error:
        print(f"edition revision error: {arguments.provider}/{arguments.document}: {error}",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
